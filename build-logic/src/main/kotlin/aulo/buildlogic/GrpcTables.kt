package aulo.buildlogic

import com.squareup.wire.schema.Extend
import com.squareup.wire.schema.Field
import com.squareup.wire.schema.ProtoFile
import com.squareup.wire.schema.ProtoType
import com.squareup.wire.schema.Rpc
import com.squareup.wire.schema.Schema
import com.squareup.wire.schema.SchemaHandler
import com.squareup.wire.schema.Service
import com.squareup.wire.schema.Type
import com.squareup.wire.schema.internal.SchemaEncoder
import okio.Path

/**
 * Writes what Kotlin/Native cannot reflect from Wire's generated services: for every service an
 * extension that maps each method path to a transport handler, and the file descriptors that
 * server reflection serves. Options: `package` for the output, `runtime` for the package that
 * defines `unary`, `clientStreaming`, `serverStreaming` and `bidiStreaming`.
 */
class GrpcTablesFactory : SchemaHandler.Factory {
    override fun create(
        includes: List<String>,
        excludes: List<String>,
        exclusive: Boolean,
        outDirectory: String,
        options: Map<String, String>,
    ): SchemaHandler =
        GrpcTablesHandler(
            outPackage = options["package"] ?: error("GrpcTablesFactory needs the `package` option"),
            runtime = options["runtime"] ?: error("GrpcTablesFactory needs the `runtime` option"),
        )
}

class GrpcTablesHandler(
    private val outPackage: String,
    private val runtime: String,
) : SchemaHandler() {
    override fun handle(
        schema: Schema,
        context: Context,
    ) {
        val text = GrpcTables.render(schema, schema.protoFiles.filter { context.inSourcePath(it) }, outPackage, runtime)
        val dir = outPackage.split('.').fold(context.outDirectory) { path, part -> path / part }
        context.fileSystem.createDirectories(dir)
        context.fileSystem.write(dir / "GrpcTables.kt") { writeUtf8(text) }
    }

    // Everything happens in handle(schema): one file covers every service.
    override fun handle(
        type: Type,
        context: Context,
    ): Path? = null

    override fun handle(
        service: Service,
        context: Context,
    ): List<Path> = emptyList()

    override fun handle(
        extend: Extend,
        field: Field,
        context: Context,
    ): Path? = null
}

object GrpcTables {
    fun render(
        schema: Schema,
        sources: List<ProtoFile>,
        outPackage: String,
        runtime: String,
    ): String {
        val files = reachable(schema, sources)
        val encoder = SchemaEncoder(schema)
        val out = StringBuilder()
        out.appendLine("// Code generated by aulo's GrpcTablesHandler (build-logic), do not edit.")
        out.appendLine()
        out.appendLine("package $outPackage")
        out.appendLine()
        for (file in sources) {
            for (service in file.services) {
                out.appendLine(
                    "internal fun ${kotlinName(
                        schema,
                        service.type,
                        suffix = "Server",
                    )}.grpcHandlers(): Map<String, aulo.grpc.ServerHandler> =",
                )
                out.appendLine("    mapOf(")
                for (rpc in service.rpcs) out.appendLine("        ${handlerEntry(schema, service, rpc, runtime)},")
                out.appendLine("    )")
                out.appendLine()
            }
        }
        out.appendLine("/** The proto files of this module and their imports, for server reflection. */")
        out.appendLine("internal object GrpcSchema {")
        out.appendLine("    /** File name to its imports. */")
        out.appendLine("    val imports: Map<String, List<String>> =")
        out.appendLine("        mapOf(")
        for (file in files) {
            val imports = (file.imports + file.publicImports).distinct().joinToString { "\"$it\"" }
            out.appendLine("            \"${file.location.path}\" to listOf($imports),")
        }
        out.appendLine("        )")
        out.appendLine()
        out.appendLine("    /** Fully qualified service, method, message and enum names to the file that declares them. */")
        out.appendLine("    val symbols: Map<String, String> =")
        out.appendLine("        mapOf(")
        for (file in files) {
            for ((symbol, path) in symbols(file)) out.appendLine("            \"$symbol\" to \"$path\",")
        }
        out.appendLine("        )")
        out.appendLine()
        out.appendLine("    /** File name to its FileDescriptorProto, base64. */")
        out.appendLine("    val descriptors: Map<String, String> =")
        out.appendLine("        mapOf(")
        for (file in files) out.appendLine("            \"${file.location.path}\" to \"${encoder.encode(file).base64()}\",")
        out.appendLine("        )")
        out.appendLine("}")
        return out.toString()
    }

    /** The source files and everything they import, in a stable order. */
    private fun reachable(
        schema: Schema,
        sources: List<ProtoFile>,
    ): List<ProtoFile> {
        val seen = LinkedHashMap<String, ProtoFile>()

        fun visit(file: ProtoFile) {
            if (seen.putIfAbsent(file.location.path, file) != null) return
            for (name in file.imports + file.publicImports) {
                visit(schema.protoFile(name) ?: error("${file.location.path} imports missing $name"))
            }
        }
        sources.sortedBy { it.location.path }.forEach(::visit)
        return seen.values.sortedBy { it.location.path }
    }

    private fun symbols(file: ProtoFile): List<Pair<String, String>> {
        val path = file.location.path
        val out = mutableListOf<Pair<String, String>>()
        for (service in file.services) {
            out += service.type.toString() to path
            for (rpc in service.rpcs) out += "${service.type}.${rpc.name}" to path
        }

        fun type(t: Type) {
            out += t.type.toString() to path
            t.nestedTypes.forEach(::type)
        }
        file.types.forEach(::type)
        return out
    }

    private fun handlerEntry(
        schema: Schema,
        service: Service,
        rpc: Rpc,
        runtime: String,
    ): String {
        val path = "/${service.type}/${rpc.name}"
        val request = "${kotlinName(schema, rpc.requestType!!)}.ADAPTER"
        val response = "${kotlinName(schema, rpc.responseType!!)}.ADAPTER"
        val (shape, params) =
            when {
                rpc.requestStreaming && rpc.responseStreaming -> "bidiStreaming" to "requests, responses"
                rpc.requestStreaming -> "clientStreaming" to "requests"
                rpc.responseStreaming -> "serverStreaming" to "request, responses"
                else -> "unary" to "request"
            }
        return "\"$path\" to $runtime.$shape($request, $response) { $params -> ${rpc.name}($params) }"
    }

    /**
     * The Kotlin name Wire gives a proto type: the file's `java_package` (or its proto package),
     * then the nested names. A wrong guess fails the compile of the generated file, not at run time.
     */
    internal fun kotlinName(
        schema: Schema,
        type: ProtoType,
        suffix: String = "",
    ): String {
        val file = schema.protoFile(type) ?: error("no file declares $type")
        val protoPackage = file.packageName.orEmpty()
        val nested = type.toString().removePrefix("$protoPackage.")
        val kotlinPackage = file.javaPackage() ?: protoPackage
        return listOf(kotlinPackage, nested + suffix).filter { it.isNotEmpty() }.joinToString(".")
    }
}
